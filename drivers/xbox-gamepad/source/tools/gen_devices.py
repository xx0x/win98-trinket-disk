"""gen_devices.py XPAD_C OUT_DIR - build the XGP98 device list from Linux's xpad.c.

Reads the xpad_device[] table of drivers/input/joystick/xpad.c and writes
  OUT_DIR/source/driver/devices.h   VID/PID -> pad type, mapping quirks, flags (for xgp98.c)
  OUT_DIR/XGP98.INF                the Windows 98 INF with every supported controller
  OUT_DIR/README.md                 the table under "Supported controllers"
"""
import os, re, sys

src, out = sys.argv[1], sys.argv[2]
text = open(src, encoding='utf-8').read()
table = text[text.index('} xpad_device[] = {'):]
table = table[:table.index('};')]

MAP = {'0': 0, 'MAP_DPAD_TO_BUTTONS': 1, 'MAP_TRIGGERS_TO_BUTTONS': 2, 'MAP_STICKS_TO_NULL': 4,
       'MAP_SHARE_BUTTON': 8, 'MAP_PADDLES': 16, 'MAP_PROFILE_BUTTON': 32, 'MAP_SHARE_OFFSET': 64,
       'DANCEPAD_MAP_CONFIG': 1 | 2 | 4}
TYPE = {'XTYPE_XBOX': 0, 'XTYPE_XBOX360': 1, 'XTYPE_XBOX360W': 2, 'XTYPE_XBOXONE': 3}
FLAG = {'FLAG_DELAY_INIT': 1}
# Keyboards and keypads with an Xbox 360 gamepad function: Windows 98 installs one driver for the whole
# USB device, so listing them in the INF would take their keyboard away. Left out entirely.
KEYBOARDS = re.compile(r'^(Wooting|Azeron)\b', re.I)

def expr(s, names):
    v = 0
    for part in s.split('|'):
        part = part.strip()
        if part: v |= names[part]
    return v

devs, seen, skipped = [], set(), []
for m in re.finditer(r'\{\s*(0x[0-9a-fA-F]+),\s*(0x[0-9a-fA-F]+),\s*"((?:[^"\\]|\\.)*)",\s*([^,]+),\s*(XTYPE_\w+)\s*(?:,\s*([^}]*?))?\s*\}', table):
    vid, pid, name, mapping, xtype, flags = m.groups()
    if xtype not in TYPE: continue                  # XTYPE_UNKNOWN: the generic fallback entry
    vid, pid = int(vid, 16), int(pid, 16)
    if (vid, pid) in seen: continue
    seen.add((vid, pid))
    name = name.replace('\\"', "'").strip()
    name = ''.join(c if 32 <= ord(c) < 127 and c not in '"%' else ' ' for c in name)
    name = re.sub(r'\s+', ' ', name).strip()
    if KEYBOARDS.match(name):
        skipped.append(name); continue
    devs.append((vid, pid, name, expr(mapping, MAP), TYPE[xtype], expr(flags or '', FLAG)))
devs.sort()

# ---------------------------------------------------------------- devices.h
h = ['/* SPDX-License-Identifier: GPL-2.0-or-later */',
     '/* devices.h - generated by source/tools/gen_devices.py from Linux drivers/input/joystick/xpad.c,',
     ' * table xpad_device[] - do not edit. %d controllers. */' % len(devs),
     'typedef struct { USHORT vid, pid; UCHAR type, map, flags; } XGP_DEV;',
     'static const XGP_DEV g_devices[] = {']
for vid, pid, name, mp, ty, fl in devs:
    h.append('    { 0x%04x, 0x%04x, %d, 0x%02x, %d },   /* %s */' % (vid, pid, ty, mp, fl, name.replace('*/', '* /')))
h += ['};', '']
open(os.path.join(out, 'source', 'driver', 'devices.h'), 'w').write('\n'.join(h))

# ---------------------------------------------------------------- XGP98.INF
TYPENAME = ['Xbox', 'Xbox 360', 'Xbox 360 wireless receiver', 'Xbox One / Series']
inf = [
 '; XGP98.INF - Xbox, Xbox 360, Xbox One and Xbox Series compatible controllers (USB) for Windows 98 SE',
 '; XGP98 is an adaptation of the Linux xpad driver, GPL-2.0-or-later.',
 '; Device list generated from Linux drivers/input/joystick/xpad.c (%d controllers) - see source/tools/gen_devices.py' % len(devs),
 '',
 '[Version]',
 'Signature="$CHICAGO$"',
 'Class=HID',
 'ClassGUID={745a17a0-74d3-11d0-b6fe-00a0c90f57da}',
 'Provider=%Provider%',
 '',
 '[ControlFlags]',
 'ExcludeFromSelect=*',
 '',
 '[Manufacturer]',
 '%Mfg%=XGP98.Models',
 '',
 '[XGP98.Models]']
for vid, pid, name, mp, ty, fl in devs:
    inf.append('%%D%04X_%04X%%=XGP98,USB\\VID_%04X&PID_%04X' % (vid, pid, vid, pid))
inf += ['',
 '[XGP98]',
 'CopyFiles=XGP98.Copy',
 'AddReg=XGP98.AddReg,XGP98.Names',
 '',
 '[DestinationDirs]',
 'XGP98.Copy=10,system32\\drivers',
 '',
 '[XGP98.Copy]',
 'xgp98.sys',
 '',
 '[XGP98.AddReg]',
 'HKR,,DevLoader,,*ntkern',
 'HKR,,NTMPDriver,,xgp98.sys',
 '',
 '; names shown in Control Panel - Game Controllers',
 '[XGP98.Names]']
for vid, pid, name, mp, ty, fl in devs:
    inf.append('HKLM,%%J%%\\VID_%04X&PID_%04X,OEMName,,%%D%04X_%04X%%' % (vid, pid, vid, pid))
inf += ['',
 '[SourceDisksNames]',
 '1=%Disk%,,0',
 '',
 '[SourceDisksFiles]',
 'xgp98.sys=1',
 '',
 '[Strings]',
 'Provider="XGP98"',
 'Mfg="Xbox compatible controllers (XGP98)"',
 'Disk="XGP98 driver disk"',
 'J="System\\CurrentControlSet\\Control\\MediaProperties\\PrivateProperties\\Joystick\\OEM"']
for vid, pid, name, mp, ty, fl in devs:
    inf.append('D%04X_%04X="%s"' % (vid, pid, name))
data = ('\r\n'.join(inf) + '\r\n').encode('ascii')
assert len(data) < 60000, 'XGP98.INF is %d bytes - Windows 98 setup cannot read INF files over 64 KB' % len(data)
open(os.path.join(out, 'XGP98.INF'), 'wb').write(data)

# ---------------------------------------------------------------- README list
lst = ['| VID:PID | Controller | Type |', '|---|---|---|']
for vid, pid, name, mp, ty, fl in devs:
    lst.append('| %04X:%04X | %s | %s |' % (vid, pid, name.replace('|', '\\|'), TYPENAME[ty]))
readme = os.path.join(out, 'README.md')          # replace the table in "## Supported controllers"
if os.path.exists(readme):
    r = open(readme, encoding='utf-8').read()
    i = r.index('| VID:PID | Controller | Type |'); j = r.find('\n\n## ', i)   # up to the next section
    r = r[:i] + '\n'.join(lst) + (r[j:] if j >= 0 else '\n')
    r = re.sub(r"All controllers of `xpad`'s device table \(\d+\)", "All controllers of `xpad`'s device table (%d)" % len(devs), r)
    r = re.sub(r'The full list of \d+ supported controllers', 'The full list of %d supported controllers' % len(devs), r)
    open(readme, 'w', encoding='utf-8').write(r)
print('left out (keyboards/keypads): %d' % len(skipped))
print('%d controllers: %s' % (len(devs), ', '.join('%s %d' % (TYPENAME[t], sum(1 for d in devs if d[4] == t)) for t in range(4))))
